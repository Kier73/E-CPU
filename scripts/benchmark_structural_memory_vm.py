#!/usr/bin/env python3
"""Compare resident MailCPU pages with Structural Memory-backed reservations.

The experiment holds VM count, virtual address space, page geometry, working set,
and data bytes constant. It reports resident pages, reserved pages, checkpoint
size, Structural Memory provenance state, cold fault cost, hot access cost, and
post-restore fault cost separately. It does not count symbolic reservations as
resident memory or assume that symbolic reads are free.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from time import perf_counter_ns
from typing import Any, Sequence

from mailcpu import HeadlessOS, Instruction, Op, Program, StructuralMemoryFileRef
from mailcpu.law_certifier import Law

SCHEMA = "mailcpu.structural-memory-vm-comparison.v1"
BYTE_DOMAIN = "byte-stream"
DEFAULT_PAGE_SIZE = 4096


class StructuralMemoryBenchmarkError(RuntimeError):
    """The paired memory-tier experiment failed a state, content, or restore invariant."""


def _canonical_bytes(value: Any) -> bytes:
    """Mathematics: encode the measured checkpoint projection with one injective canonical JSON representation."""
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def _page_bytes(page_index: int, page_size: int) -> bytes:
    """Mathematics: generate immutable test page b_i[j]=(29i+j) mod 256."""
    seed = (page_index * 29) & 0xFF
    return bytes((seed + offset) & 0xFF for offset in range(page_size))


def _structural_admission_policy(proposal: Any) -> bool:
    """Mathematics: admit only byte-stream descriptions into this benchmark's receiver-local Structural Memory Ground."""
    return getattr(getattr(proposal, "spec", None), "domain", None) == BYTE_DOMAIN


def _register_structural_pages(
    operating_system: HeadlessOS,
    page_count: int,
    page_size: int,
) -> tuple[str, ...]:
    """Mathematics: construct one admitted integer orbit per page and bind its hash to the exact generated byte range."""
    digests: list[str] = []
    for page_index in range(page_count):
        seed = (page_index * 29) & 0xFF
        law = Law(
            family="int",
            params={"x0": seed, "step": 1, "mod": 256},
            order=1,
            verdict="GROUND",
        )
        witnesses = {
            coordinate: (seed + coordinate) & 0xFF
            for coordinate in range(8)
        }
        memory_id = f"vm-capacity-page-{page_index:04d}"
        proposal = operating_system.structural_memory.propose(
            memory_id,
            law,
            witnesses,
            domain=BYTE_DOMAIN,
            context={
                "benchmark": "structural-memory-vm-capacity",
                "page_index": page_index,
                "encoding": "modulo-256-byte-stream",
            },
        )
        version = operating_system.structural_memory.admit(
            proposal.proposal_id,
            expected_revision=0,
        )
        reference = StructuralMemoryFileRef.from_version(
            version,
            coordinate_start=0,
            size=page_size,
        )
        expected = _page_bytes(page_index, page_size)
        digest = hashlib.sha256(expected).hexdigest()
        operating_system.register_structural_memory_page(digest, reference)
        digests.append(digest)
    return tuple(digests)


def _make_case(
    mode: str,
    *,
    page_size: int,
    virtual_pages: int,
    working_set_pages: int,
    hot_repetitions: int,
) -> dict[str, Any]:
    """Run one memory tier with an identical VM geometry and access working set."""
    if mode not in {"materialized", "structural"}:
        raise ValueError("mode must be materialized or structural")
    operating_system = HeadlessOS(
        max_resident_pages=virtual_pages,
        structural_memory_admission_policy=_structural_admission_policy,
    )
    pid = operating_system.vm.spawn_program(
        Program((Instruction(Op.HALT),)),
        f"structural-memory-{mode}",
        page_size=page_size,
        max_pages=virtual_pages,
    )
    memory = operating_system.vm.memories[pid]

    # Replace the two default process pages with one identical explicit virtual
    # interval so both cases begin with exactly the same address-space geometry.
    memory.unmap(0, 2 * page_size)
    digests: tuple[str, ...] = ()
    if mode == "structural":
        digests = _register_structural_pages(
            operating_system,
            virtual_pages,
            page_size,
        )
        memory.reserve(
            0,
            virtual_pages * page_size,
            writable=False,
            backing_blob_ids=digests,
        )
    else:
        memory.reserve(
            0,
            virtual_pages * page_size,
            writable=True,
            backing_blob_ids=(None,) * virtual_pages,
        )
        for page_index in range(virtual_pages):
            # Demand-materialize through the normal page-reservation path so
            # the VM's resident-page admission callback is applied.
            memory.write(
                page_index * page_size,
                _page_bytes(page_index, page_size),
            )

    before_access_mapped = len(memory.mapped_pages())
    before_access_reserved = len(memory.reserved_pages())
    if before_access_mapped + before_access_reserved != virtual_pages:
        raise StructuralMemoryBenchmarkError("virtual page count changed during case construction")

    cold_access_ns: list[int] = []
    for page_index in range(working_set_pages):
        started = perf_counter_ns()
        actual = memory.read(page_index * page_size, page_size)
        elapsed = perf_counter_ns() - started
        cold_access_ns.append(elapsed)
        expected = _page_bytes(page_index, page_size)
        if actual != expected:
            raise StructuralMemoryBenchmarkError(
                f"{mode} page {page_index} did not reproduce its declared bytes"
            )

    resident_after_cold = operating_system.vm.resident_pages()
    reserved_after_cold = len(memory.reserved_pages())
    mapped_after_cold = len(memory.mapped_pages())
    page_backing = operating_system.vm.page_backing
    backing_cached_page_count = int(
        getattr(page_backing, "cached_page_count", 0)
    )
    backing_cached_page_bytes = int(
        getattr(page_backing, "cached_page_bytes", 0)
    )
    backing_cached_receipt_coordinate_count = int(
        getattr(page_backing, "cached_receipt_coordinate_count", 0)
    )
    backing_cached_provider_coordinate_count = int(
        getattr(page_backing, "cached_provider_coordinate_count", 0)
    )
    if mapped_after_cold + reserved_after_cold != virtual_pages:
        raise StructuralMemoryBenchmarkError("cold accesses changed the virtual page count")

    hot_access_ns: list[int] = []
    for _ in range(hot_repetitions):
        for page_index in range(working_set_pages):
            started = perf_counter_ns()
            actual = memory.read(page_index * page_size, page_size)
            hot_access_ns.append(perf_counter_ns() - started)
            if actual != _page_bytes(page_index, page_size):
                raise StructuralMemoryBenchmarkError("hot access changed page content")

    # Force one resident->reserved->resident cycle. The structural mode should
    # reuse its measured host cache, while the materialized control uses local
    # content backing. Both must return the same page and keep the same owner.
    cache_probe_before_hits = int(getattr(page_backing, "cached_reuse_count", 0))
    reclaim_started = perf_counter_ns()
    memory.reclaim(count=1, page_numbers=(0,))
    cache_probe_reclaim_ns = perf_counter_ns() - reclaim_started
    resident_cache_overlap_after_reclaim = int(
        getattr(page_backing, "shared_resident_cache_bytes", lambda _blobs: 0)(
            memory._blobs
        )
    )
    cached_page_bytes_after_reclaim = int(
        getattr(page_backing, "cached_page_bytes", 0)
    )
    backing_only_retained_bytes_after_reclaim = (
        cached_page_bytes_after_reclaim - resident_cache_overlap_after_reclaim
    )
    refault_started = perf_counter_ns()
    cache_probe_bytes = memory.read(0, page_size)
    cache_probe_refault_ns = perf_counter_ns() - refault_started
    cache_probe_ns = cache_probe_reclaim_ns + cache_probe_refault_ns
    cache_probe_content_valid = cache_probe_bytes == _page_bytes(0, page_size)
    cache_probe_after_hits = int(getattr(page_backing, "cached_reuse_count", 0))
    cache_probe_hit_delta = cache_probe_after_hits - cache_probe_before_hits
    resident_cache_overlap_after_refault = int(
        getattr(page_backing, "shared_resident_cache_bytes", lambda _blobs: 0)(
            memory._blobs
        )
    )
    if not cache_probe_content_valid:
        raise StructuralMemoryBenchmarkError("page cache probe changed the declared bytes")
    if mode == "structural" and cache_probe_hit_delta != 2:
        raise StructuralMemoryBenchmarkError(
            "structural page reclaim/refault did not reuse the bounded host page cache twice"
        )
    backing_cached_page_count_after_probe = int(
        getattr(page_backing, "cached_page_count", 0)
    )
    backing_cached_page_bytes_after_probe = int(
        getattr(page_backing, "cached_page_bytes", 0)
    )
    backing_cached_receipt_coordinate_count_after_probe = int(
        getattr(page_backing, "cached_receipt_coordinate_count", 0)
    )
    backing_cached_provider_coordinate_count_after_probe = int(
        getattr(page_backing, "cached_provider_coordinate_count", 0)
    )
    backing_cached_regeneration_cost_ns_after_probe = int(
        getattr(page_backing, "cached_regeneration_cost_ns", 0)
    )
    backing_cache_retention_policy = str(
        getattr(page_backing, "cache_retention_policy", "none")
    )

    snapshot_started = perf_counter_ns()
    snapshot = operating_system.snapshot()
    snapshot_ns = perf_counter_ns() - snapshot_started
    checkpoint_bytes = len(_canonical_bytes(snapshot))
    page_backing_state = snapshot["vm"].get("page_backing_state", {})
    structural_registry_state = snapshot.get("structural_memory", {})
    page_backing_descriptor_bytes = len(_canonical_bytes(page_backing_state))
    structural_registry_bytes = len(_canonical_bytes(structural_registry_state))
    structural_range_events = [
        record
        for record in snapshot["vm"]["environment"]["kernel"]["journal"]
        if record.get("kind") == "structural_memory.read_revision_range"
    ]
    structural_range_event_count = len(structural_range_events)
    structural_coordinate_commitment_count = sum(
        int(record["payload"]["receipt"]["length"])
        for record in structural_range_events
    )
    if mode == "structural":
        backing = operating_system.vm.page_backing
        provider_coordinate_receipt_count = sum(
            len(backing.read_receipt(digests[page_index]).value_receipt_ids)
            for page_index in range(working_set_pages)
        )
        if provider_coordinate_receipt_count != structural_coordinate_commitment_count:
            raise StructuralMemoryBenchmarkError(
                "provider value receipts do not match the durable range commitments"
            )
    else:
        provider_coordinate_receipt_count = 0

    restore_started = perf_counter_ns()
    restored = HeadlessOS.from_snapshot(
        snapshot,
        structural_memory_admission_policy=_structural_admission_policy,
    )
    restore_ns = perf_counter_ns() - restore_started
    restored_memory = restored.vm.memories[pid]
    restore_state_preserved = (
        restored.vm.resident_pages() == resident_after_cold
        and len(restored_memory.mapped_pages()) == mapped_after_cold
        and len(restored_memory.reserved_pages()) == reserved_after_cold
        and restored_memory.max_pages == virtual_pages
        and restored.environment.kernel.journal.verify()
    )
    if not restore_state_preserved:
        raise StructuralMemoryBenchmarkError(f"{mode} restore did not preserve mappings, reservations, or journal")

    # Touch one previously untouched page after restore. The materialized
    # control is already resident; the structural case must rebind its local
    # registry and resolve the revision-pinned byte generator again.
    restore_fault_page = working_set_pages if working_set_pages < virtual_pages else 0
    restore_fault_started = perf_counter_ns()
    restored_bytes = restored_memory.read(
        restore_fault_page * page_size,
        page_size,
    )
    restore_fault_ns = perf_counter_ns() - restore_fault_started
    restored_page_content_valid = restored_bytes == _page_bytes(restore_fault_page, page_size)
    if not restored_page_content_valid:
        raise StructuralMemoryBenchmarkError(f"{mode} post-restore page fault returned incorrect bytes")

    receipt_present = False
    if mode == "structural":
        backing = restored.vm.page_backing
        receipt_present = (
            callable(getattr(backing, "read_receipt", None))
            and backing.read_receipt(digests[restore_fault_page]) is not None
        )
        if not receipt_present:
            raise StructuralMemoryBenchmarkError("restored structural page fault did not retain a read receipt")

    journal_valid_after_restore_fault = restored.environment.kernel.journal.verify()
    if not journal_valid_after_restore_fault:
        raise StructuralMemoryBenchmarkError("journal failed verification after the post-restore page fault")

    return {
        "mode": mode,
        "virtual_pages": virtual_pages,
        "virtual_bytes": virtual_pages * page_size,
        "page_size_bytes": page_size,
        "working_set_pages": working_set_pages,
        "working_set_bytes": working_set_pages * page_size,
        "resident_pages_before_access": before_access_mapped,
        "reserved_pages_before_access": before_access_reserved,
        "resident_pages_after_cold_access": resident_after_cold,
        "resident_bytes_after_cold_access": resident_after_cold * page_size,
        "reserved_pages_after_cold_access": reserved_after_cold,
        "reserved_bytes_after_cold_access": reserved_after_cold * page_size,
        "host_backing_cached_page_count_after_cold_access": backing_cached_page_count,
        "host_backing_cached_page_bytes_after_cold_access": backing_cached_page_bytes,
        "host_backing_cached_receipt_coordinate_count_after_cold_access": backing_cached_receipt_coordinate_count,
        "host_backing_cached_provider_coordinate_count_after_cold_access": backing_cached_provider_coordinate_count,
        "cache_probe_wall_ns": cache_probe_ns,
        "cache_probe_reclaim_wall_ns": cache_probe_reclaim_ns,
        "cache_probe_refault_wall_ns": cache_probe_refault_ns,
        "cache_probe_page_content_valid": cache_probe_content_valid,
        "host_backing_cached_page_bytes_after_reclaim": cached_page_bytes_after_reclaim,
        "host_backing_shared_resident_cache_bytes_after_reclaim": resident_cache_overlap_after_reclaim,
        "host_backing_only_retained_page_bytes_after_reclaim": backing_only_retained_bytes_after_reclaim,
        "host_backing_shared_resident_cache_bytes_after_refault": resident_cache_overlap_after_refault,
        "host_backing_cached_page_count_after_probe": backing_cached_page_count_after_probe,
        "host_backing_cached_page_bytes_after_probe": backing_cached_page_bytes_after_probe,
        "host_backing_cached_receipt_coordinate_count_after_probe": backing_cached_receipt_coordinate_count_after_probe,
        "host_backing_cached_provider_coordinate_count_after_probe": backing_cached_provider_coordinate_count_after_probe,
        "host_backing_cached_reuse_count_after_probe": cache_probe_after_hits,
        "host_backing_cache_probe_hit_delta": cache_probe_hit_delta,
        "host_backing_cached_regeneration_cost_ns_after_probe": backing_cached_regeneration_cost_ns_after_probe,
        "host_backing_cache_retention_policy": backing_cache_retention_policy,
        "cold_page_access_ns": cold_access_ns,
        "cold_page_access_mean_ns": (
            sum(cold_access_ns) // len(cold_access_ns) if cold_access_ns else 0
        ),
        "hot_access_ns": hot_access_ns,
        "hot_access_mean_ns": (
            sum(hot_access_ns) // len(hot_access_ns) if hot_access_ns else 0
        ),
        "snapshot_wall_ns": snapshot_ns,
        "checkpoint_restore_wall_ns": restore_ns,
        "checkpoint_bytes": checkpoint_bytes,
        "page_backing_descriptor_bytes": page_backing_descriptor_bytes,
        "structural_registry_bytes": structural_registry_bytes,
        "structural_registry_point_cache_entry_count": len(
            structural_registry_state.get("read_cache", ())
        ),
        "structural_range_read_event_count": structural_range_event_count,
        "structural_coordinate_commitment_count": structural_coordinate_commitment_count,
        "provider_coordinate_receipt_count": provider_coordinate_receipt_count,
        "post_restore_fault_page": restore_fault_page,
        "post_restore_fault_wall_ns": restore_fault_ns,
        "post_restore_fault_resident_delta": (
            restored.vm.resident_pages() - resident_after_cold
        ),
        "post_restore_fault_receipt_verified": receipt_present,
        "restore_state_preserved": restore_state_preserved,
        "restored_page_content_valid": restored_page_content_valid,
        "journal_valid_after_restore_fault": journal_valid_after_restore_fault,
    }


def benchmark_pair(
    *,
    page_size: int = DEFAULT_PAGE_SIZE,
    virtual_pages: int = 4,
    working_set_pages: int = 2,
    hot_repetitions: int = 5,
) -> dict[str, Any]:
    """Compare materialized and symbolic page tiers under the same virtual size and working set."""
    for name, value, minimum in (
        ("page_size", page_size, 256),
        ("virtual_pages", virtual_pages, 2),
        ("working_set_pages", working_set_pages, 1),
        ("hot_repetitions", hot_repetitions, 1),
    ):
        if type(value) is not int or value < minimum:
            raise ValueError(f"{name} must be an integer >= {minimum}")
    if page_size & (page_size - 1) or page_size > 65_536:
        raise ValueError("page_size must be a power of two no larger than 65536")
    if working_set_pages >= virtual_pages:
        raise ValueError(
            "working_set_pages must be less than virtual_pages to leave a cold restore page"
        )

    materialized = _make_case(
        "materialized",
        page_size=page_size,
        virtual_pages=virtual_pages,
        working_set_pages=working_set_pages,
        hot_repetitions=hot_repetitions,
    )
    structural = _make_case(
        "structural",
        page_size=page_size,
        virtual_pages=virtual_pages,
        working_set_pages=working_set_pages,
        hot_repetitions=hot_repetitions,
    )
    same_virtual_geometry = (
        materialized["virtual_bytes"] == structural["virtual_bytes"]
        and materialized["working_set_bytes"] == structural["working_set_bytes"]
    )
    if not same_virtual_geometry:
        raise StructuralMemoryBenchmarkError("paired cases did not use identical virtual geometry")

    resident_page_reduction = (
        materialized["resident_pages_after_cold_access"]
        - structural["resident_pages_after_cold_access"]
    )
    return {
        "schema": SCHEMA,
        "repository": "Kier73/E-CPU",
        "profile": {
            "page_size_bytes": page_size,
            "virtual_pages_per_vm": virtual_pages,
            "working_set_pages": working_set_pages,
            "hot_repetitions": hot_repetitions,
            "vm_definition": "one HeadlessOS + one MailCPUVirtualMachine + one scheduler + one kernel + one process memory",
            "workload": "same deterministic page bytes and read working set in both cases",
        },
        "comparison": {
            "same_virtual_geometry": same_virtual_geometry,
            "materialized_resident_pages": materialized["resident_pages_after_cold_access"],
            "structural_resident_pages": structural["resident_pages_after_cold_access"],
            "resident_page_reduction": resident_page_reduction,
            "resident_byte_reduction": resident_page_reduction * page_size,
            "structural_reserved_pages_after_cold_access": structural["reserved_pages_after_cold_access"],
            "structural_reserved_bytes_after_cold_access": structural["reserved_bytes_after_cold_access"],
            "physical_host_capacity_claim": (
                "not established; Structural Memory reservations are virtual descriptors, "
                "resident pages are VM mappings, and host RSS is not measured by this paired guest-memory experiment"
            ),
        },
        "cases": {
            "materialized": materialized,
            "structural": structural,
        },
    }


def main(argv: Sequence[str] | None = None) -> int:
    """Mathematics: run one paired experiment and emit its canonical machine-readable evidence record."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--page-size", type=int, default=DEFAULT_PAGE_SIZE)
    parser.add_argument("--virtual-pages", type=int, default=4)
    parser.add_argument("--working-set-pages", type=int, default=2)
    parser.add_argument("--hot-repetitions", type=int, default=5)
    parser.add_argument("--output", type=str, default=None)
    parser.add_argument("--pretty", action="store_true")
    args = parser.parse_args(argv)
    try:
        report = benchmark_pair(
            page_size=args.page_size,
            virtual_pages=args.virtual_pages,
            working_set_pages=args.working_set_pages,
            hot_repetitions=args.hot_repetitions,
        )
    except (ValueError, StructuralMemoryBenchmarkError) as exc:
        parser.error(str(exc))
    encoded = json.dumps(
        report,
        sort_keys=True,
        indent=2 if args.pretty else None,
        ensure_ascii=False,
        allow_nan=False,
    )
    print(encoded)
    if args.output:
        with open(args.output, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(encoded)
            handle.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
