r"""$\Omega_5$ Law certifier, closed-form orbit leaper, and 8-rung algebraic ladder.

Mathematics:
Let $x = (x_0, x_1, \dots, x_{N-1}) \in \mathbb{Z}^N$ be an observation trace
generated by a discrete dynamical system. The $\Omega_5$ certifier seeks to
map the trace to the lowest sufficient rung on an 8-rung algebraic ladder:
1. $\text{int}$: Arithmetic progression $x_t \equiv (x_0 + \text{step} \cdot t) \pmod M$.
2. $\text{lcg}$: Affine linear congruential recurrence $x_{t+1} \equiv (a x_t + c) \pmod M$.
3. $\text{gf2}$: Linear recurrence over GF(2) with minimal polynomial $C(D) \in \mathbb{F}_2[D]$.
4. $\text{cfin}$: Order-$L$ linear recurrence over Galois field $\mathbb{F}_q$.
5. $\text{fgraph}$: Eventual periodic orbit of a map on a finite set ($x_{t+1} = f(x_t)$).
6. $\text{kreg}$: $k$-regular sequence with decimation relations $x_{k t + r} = \alpha_r x_t + \beta_r$.
7. $\text{strat}$: Stratified multi-layer grammar with phase transitions.
8. $\text{tape}$: Uncompressed execution trace (honest refusal / non-certifiable).

A certificate is GROUND iff it reproduces 100% of withheld verification probes;
PREFIX-GROUND iff it holds until an escape coordinate $t_{\text{horizon}} = \text{first\_bad}$;
and TAPE (refused) otherwise. Navigation past $t_{\text{horizon}}$ is prohibited.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from math import gcd
from typing import Any, Callable, Sequence


class Refused(Exception):
    r"""Honest refusal: the requested operation is mathematically undefined.

    Mathematics:
    Refusal occurs when an algebraic law is not GROUND, when an inverse lies
    beyond the computable orbit horizon, or when a requested state does not exist.
    """


class HorizonExceeded(Refused):
    r"""Navigation requested past a PREFIX-GROUND escape horizon.

    Mathematics:
    For a PREFIX-GROUND law with escape coordinate $t_{\text{horizon}} = \text{first\_bad}$,
    evaluation at $t \ge t_{\text{horizon}}$ raises HorizonExceeded to preserve truth.
    """


def geom_sum_mod(a: int, t: int, m: int) -> int:
    r"""Compute $\sum_{i=0}^{t-1} a^i \pmod m$ in $\mathcal{O}(\log t)$ time.

    Mathematics:
    \[
    S(t) = \sum_{i=0}^{t-1} a^i \pmod m
    \]
    Evaluated recursively using binary exponentiation:
    - $S(2k) = S(k) \cdot (1 + a^k) \pmod m$
    - $S(2k+1) = (a \cdot S(2k) + 1) \pmod m$
    Requires no multiplicative inverse of $(a - 1)$, ensuring validity for composite $m$.

    Args:
        a: Multiplier base.
        t: Non-negative number of terms.
        m: Modulus ring ($m \ge 1$).

    Returns:
        Geometric series sum modulo $m$.
    """
    if t <= 0 or m <= 1:
        return 0
    if t == 1:
        return 1 % m
    if t % 2 == 0:
        half = geom_sum_mod(a, t // 2, m)
        return (half * (1 + pow(a, t // 2, m))) % m
    return (a * geom_sum_mod(a, t - 1, m) + 1) % m


def lcg_navigate(a: int, c: int, m: int, x0: int, t: int) -> int:
    r"""Compute the closed-form state of an affine recurrence at coordinate $t$.

    Mathematics:
    For recurrence $x_{k+1} \equiv (a x_k + c) \pmod m$ with initial state $x_0$:
    \[
    x_t \equiv \left(a^t x_0 + c \sum_{i=0}^{t-1} a^i\right) \pmod m
    \]
    Evaluates in $\mathcal{O}(\log t)$ multiplications without intermediate state tracking.

    Args:
        a: Multiplier.
        c: Additive increment.
        m: Modulus.
        x0: Initial state at $t = 0$.
        t: Target coordinate ($t \ge 0$).

    Returns:
        State value $x_t \in [0, m - 1]$.
    """
    if m <= 1:
        return 0
    return (pow(a, t, m) * x0 + c * geom_sum_mod(a, t, m)) % m


def find_coordinate_int(step: int, mod: int, x0: int, target: int) -> int | None:
    r"""Invert an integer arithmetic progression in $\mathcal{O}(1)$ time.

    Mathematics:
    Solves for smallest $t \ge 0$ such that:
    \[
    x_0 + \text{step} \cdot t \equiv \text{target} \pmod m
    \]
    Let $g = \gcd(\text{step}, m)$ and $\Delta = (\text{target} - x_0) \pmod m$.
    A solution exists iff $g \mid \Delta$. Dividing by $g$ yields:
    \[
    t \equiv \left(\frac{\Delta}{g} \cdot \left(\frac{\text{step}}{g}\right)^{-1}\right) \pmod{\frac{m}{g}}
    \]

    Args:
        step: Difference step.
        mod: Modulus.
        x0: Initial state at $t = 0$.
        target: Target value to locate.

    Returns:
        Smallest coordinate $t \ge 0$, or None if target is unreachable.
    """
    diff = (target - x0) % mod
    g = gcd(step, mod)
    if diff % g != 0:
        return None
    step_p = step // g
    mod_p = mod // g
    return ((diff // g) * pow(step_p, -1, mod_p)) % mod_p


def find_coordinate_lcg_adic(a: int, c: int, m: int, x0: int, target: int) -> int | None:
    r"""Invert a full-period power-of-two LCG in $\mathcal{O}(\log m)$ bit-lifting steps.

    Mathematics:
    For $m = 2^r$ with $a \equiv 1 \pmod 4$ and $c$ odd, the sequence has full period $2^r$.
    The differences $d_t = x_{t+1} - x_t = (a - 1) x_t + c$ satisfy $d_t = a^t d_0 \pmod m$.
    Both $d_0$ and $d_t = (a - 1) \text{target} + c \pmod m$ are odd units.
    Solving $a^t \equiv d_t d_0^{-1} \pmod{2^r}$ recovers $t \pmod{2^{r-2}}$ bit-by-bit in $r - 2$ steps.
    Disambiguates the 4 cycle shifts in $\mathcal{O}(1)$ forward checks.

    Args:
        a: Multiplier ($a \equiv 1 \pmod 4$).
        c: Odd additive increment.
        m: Power-of-two modulus $2^r$.
        x0: Initial state.
        target: Target state to find.

    Returns:
        Coordinate $t \in [0, m - 1]$, or None if target is off-orbit.
    """
    if gcd(a, m) != 1 or m < 8 or (m & (m - 1)) != 0 or (a % 4) != 1:
        return None
    r = m.bit_length() - 1
    order_bits = r - 2
    d0 = ((a - 1) * x0 + c) % m
    dt = ((a - 1) * target + c) % m
    if gcd(d0, m) != 1 or gcd(dt, m) != 1:
        return None
    ratio = (dt * pow(d0, -1, m)) % m
    s = 0
    for k in range(order_bits):
        apk = pow(a, 1 << k, m)
        mask = (1 << (k + 3)) - 1
        inv_as = pow(pow(a, s, m), -1, m)
        residue = ((ratio * inv_as) % m) & mask
        if residue == (1 & mask):
            bit = 0
        elif residue == (apk & mask):
            bit = 1
        else:
            return None
        s += bit << k

    step_shift = 1 << order_bits
    for k in range(4):
        cand_t = s + k * step_shift
        if cand_t < m and lcg_navigate(a, c, m, x0, cand_t) == target:
            return cand_t
    return None


def find_coordinate_lcg(a: int, c: int, m: int, x0: int, target: int, max_order: int | None = None) -> int | None:
    r"""Invert an affine recurrence via baby-step giant-step in $\mathcal{O}(\sqrt{m})$ time.

    Mathematics:
    Solves $x_t \equiv \text{target} \pmod m$ by choosing $M_{\text{step}} = \lceil \sqrt{\text{order}} \rceil + 1$.
    Precomputes $M_{\text{step}}$ baby steps forward from $x_0$, and computes giant steps
    backward from target using the inverse map $x \mapsto a^{-1}(x - c) \pmod m$.

    Args:
        a: Multiplier coprime to $m$.
        c: Additive increment.
        m: Modulus.
        x0: Initial state.
        target: Target state.
        max_order: Maximum search orbit bound (defaults to $m$).

    Returns:
        Smallest coordinate $t \ge 0$, or None if not found.
    """
    if gcd(a, m) != 1:
        return None
    bound = max_order if max_order is not None else m
    step_sz = math.isqrt(max(1, bound)) + 1
    a_inv = pow(a, -1, m)
    c_inv = (-a_inv * c) % m

    baby: dict[int, int] = {}
    cur = x0
    for j in range(step_sz):
        if cur not in baby:
            baby[cur] = j
        cur = (a * cur + c) % m

    for i in range(step_sz + 1):
        cand = lcg_navigate(a_inv, c_inv, m, target, i * step_sz)
        if cand in baby:
            cand_t = i * step_sz + baby[cand]
            if lcg_navigate(a, c, m, x0, cand_t) == target:
                return cand_t
    return None


def berlekamp_massey(s: Sequence[int], q: int = 2) -> tuple[list[int], int]:
    r"""Execute Berlekamp-Massey algorithm over Galois field $\mathbb{F}_q$.

    Mathematics:
    Given sequence $s = (s_0, s_1, \dots, s_{N-1}) \in \mathbb{F}_q^N$, finds the
    minimal connection polynomial $C(D) = 1 + c_1 D + \dots + c_L D^L$ of degree
    $L$ such that:
    \[
    s_n + \sum_{i=1}^L c_i s_{n-i} \equiv 0 \pmod q, \quad \forall n \ge L
    \]

    Args:
        s: Input sequence over $\mathbb{F}_q$.
        q: Field characteristic / modulus (prime).

    Returns:
        Tuple of (connection coefficients $C$, linear complexity $L$).
    """
    c = [1]
    b = [1]
    l = 0
    m = 1
    b_val = 1
    for n, sn in enumerate(s):
        d = sn % q
        for i in range(1, l + 1):
            d = (d + c[i] * s[n - i]) % q
        if d == 0:
            m += 1
        else:
            t = list(c)
            coef = (d * pow(b_val, -1, q)) % q
            need = len(b) + m
            if len(c) < need:
                c += [0] * (need - len(c))
            for j, bj in enumerate(b):
                c[j + m] = (c[j + m] - coef * bj) % q
            if 2 * l <= n:
                l = n + 1 - l
                b = t
                b_val = d
                m = 1
            else:
                m += 1
    return [coef % q for coef in c[: l + 1]], l


def lfsr_jump(c: Sequence[int], state: Sequence[int], k: int) -> list[int]:
    r"""Advance an LFSR register by $k$ steps over $\mathbb{F}_2$ in $\mathcal{O}(L^3 \log k)$ time.

    Mathematics:
    Constructs companion transition matrix $M \in \mathbb{F}_2^{L \times L}$ where:
    \[
    M_{i, i+1} = 1, \quad M_{L-1, L-j} = C_j
    \]
    Computes $M^k \cdot \text{state} \pmod 2$ via binary matrix exponentiation.

    Args:
        c: 1-indexed feedback connection coefficients ($C_0 = 1$).
        state: Initial register state vector of length $L$.
        k: Non-negative jump distance.

    Returns:
        Advanced state vector of length $L$.
    """
    n = len(state)
    if n == 0 or k <= 0:
        return list(state)
    mat = [[0] * n for _ in range(n)]
    for i in range(n - 1):
        mat[i][i + 1] = 1
    for j in range(1, min(len(c), n + 1)):
        if c[j]:
            mat[n - 1][n - j] ^= 1

    def mm(a_mat: list[list[int]], b_mat: list[list[int]]) -> list[list[int]]:
        r"""Multiply two binary square matrices over GF(2)."""
        r_mat = [[0] * n for _ in range(n)]
        for i_idx in range(n):
            ai = a_mat[i_idx]
            for j_idx in range(n):
                acc = 0
                for k_idx in range(n):
                    acc ^= ai[k_idx] & b_mat[k_idx][j_idx]
                r_mat[i_idx][j_idx] = acc
        return r_mat

    acc_mat = [[1 if i == j else 0 for j in range(n)] for i in range(n)]
    base_mat = [row[:] for row in mat]
    remaining = k
    while remaining:
        if remaining & 1:
            acc_mat = mm(acc_mat, base_mat)
        remaining >>= 1
        if remaining:
            base_mat = mm(base_mat, base_mat)

    return [sum(acc_mat[i][j] & state[j] for j in range(n)) & 1 for i in range(n)]


def brent_cycle(step_fn: Callable[[int], int], x0: int, limit: int = 1 << 22) -> tuple[int, int] | None:
    r"""Discover pre-period $\mu$ and cycle length $\lambda$ via Brent's algorithm.

    Mathematics:
    For an iterative map $x_{k+1} = f(x_k)$ on a finite set, discovers collision
    in $\mathcal{O}(\mu + \lambda)$ evaluations and $\mathcal{O}(1)$ memory:
    \[
    x_{t + \lambda} = x_t, \quad \forall t \ge \mu
    \]

    Args:
        step_fn: Deterministic step function $f(x)$.
        x0: Initial state.
        limit: Maximum iterations before giving up.

    Returns:
        Tuple of (pre-period $\mu$, cycle length $\lambda$), or None if limit exceeded.
    """
    if x0 == step_fn(x0):
        return (0, 1)
    power = lam = 1
    tortoise = x0
    hare = step_fn(x0)
    while tortoise != hare:
        if power == lam:
            tortoise = hare
            power *= 2
            lam = 0
        hare = step_fn(hare)
        lam += 1
        if power > limit:
            return None

    tortoise = hare = x0
    for _ in range(lam):
        hare = step_fn(hare)
    mu = 0
    while tortoise != hare:
        tortoise = step_fn(tortoise)
        hare = step_fn(hare)
        mu += 1
        if mu > limit:
            return None
    return (mu, lam)


def detect_eventual_period(seq: Sequence[int]) -> tuple[int, int] | None:
    r"""Detect eventual periodicity $(\mu, \lambda)$ contained in an observed window.

    Mathematics:
    Finds earliest collision $x_{\mu} = x_{\mu + \lambda}$ whose periodic repetition
    $x_{j + \lambda} = x_j$ holds across the entire remainder of the sequence,
    requiring at least two full cycles ($\text{len}(seq) - \mu \ge 2 \lambda$).

    Args:
        seq: Integer sequence.

    Returns:
        Tuple $(\mu, \lambda)$ or None if no periodic cycle covers the suffix.
    """
    if len(seq) < 4:
        return None
    seen: dict[int, int] = {}
    for i, v in enumerate(seq):
        if v in seen:
            mu = seen[v]
            lam = i - mu
            if mu + 2 * lam <= len(seq):
                ok = True
                for j in range(mu, len(seq)):
                    if seq[j] != seq[mu + (j - mu) % lam]:
                        ok = False
                        break
                if ok:
                    return (mu, lam)
        else:
            seen[v] = i
    return None


@dataclass
class Law:
    r"""Certified algebraic law over an observed trace window.

    Mathematics:
    Encapsulates generating dynamics $x_t = \mathcal{G}(t)$ across the 8-rung ladder.
    - `family`: One of `{"int", "lcg", "gf2", "cfin", "fgraph", "kreg", "strat", "tape"}`.
    - `params`: Closed-form structural parameters ($a, c, m, C, \mu, \lambda$, etc.).
    - `order`: Linear complexity or recurrence order $L$.
    - `verdict`: Certification grade `{"GROUND", "PREFIX-GROUND", "FITTED", "TAPE"}`.
    - `residual`: Unmodeled error density in $[0.0, 1.0]$.
    - `first_bad`: Escape coordinate where PREFIX-GROUND ceases to hold.
    """

    family: str
    params: dict[str, Any] = field(default_factory=dict)
    order: int = 0
    verdict: str = "TAPE"
    residual: float = 0.0
    first_bad: int | None = None

    @property
    def is_ground(self) -> bool:
        r"""Return True if the law is certified GROUND or PREFIX-GROUND."""
        return self.verdict in ("GROUND", "PREFIX-GROUND")

    def navigate(self, t: int) -> int:
        r"""Compute closed-form state at coordinate $t$.

        Mathematics:
        Evaluates $\mathcal{G}(t)$ in $\mathcal{O}(1)$ or $\mathcal{O}(\log t)$ time.
        Raises `Refused` if the law is not ground.

        Args:
            t: Target time coordinate ($t \ge 0$).

        Returns:
            Predicted integer state.
        """
        if not self.is_ground:
            raise Refused(f"law family {self.family!r} verdict {self.verdict!r} is not ground")
        fam = self.family
        p = self.params
        t_int = int(t)

        if fam == "int":
            x0 = p["x0"]
            step = p["step"]
            mod = p.get("mod")
            if mod:
                return (x0 + step * t_int) % mod
            return x0 + step * t_int

        if fam == "lcg":
            return lcg_navigate(p["a"], p["c"], p["mod"], p["x0"], t_int)

        if fam == "gf2":
            c_coef = p["C"]
            init = p["init"]
            if self.order == 0 or not init:
                return 0
            if t_int < len(init):
                return init[t_int]
            return lfsr_jump(c_coef, init, t_int)[0]

        if fam == "fgraph":
            orbit = p["orbit"]
            mu = p["mu"]
            lam = p["lam"]
            if t_int < mu:
                return orbit[t_int]
            return orbit[mu + (t_int - mu) % lam]

        if fam == "kreg":
            rules = p["rules"]
            base_vals = p["base_vals"]
            k_base = p["k"]

            def _kreg_eval(coord: int) -> int:
                r"""Evaluate k-regular recurrence recursively in O(log t)."""
                if coord in base_vals:
                    return base_vals[coord]
                r_res = coord % k_base
                q_quot = coord // k_base
                alpha, beta = rules[r_res]
                return alpha * _kreg_eval(q_quot) + beta

            return _kreg_eval(t_int)

        if fam.startswith("mixture"):
            stride = p["stride"]
            r_res = t_int % stride
            q_quot = t_int // stride
            comp = p["components"][r_res]
            sub_law = Law(
                family=comp["family"],
                params=comp["params"],
                order=comp.get("order", 1),
                verdict="GROUND",
            )
            return sub_law.navigate(q_quot)

        raise Refused(f"navigation unsupported for family {fam!r}")

    def find(self, target: int, max_order: int | None = None) -> int | None:
        r"""Invert the law to find coordinate $t$ where $\mathcal{G}(t) = \text{target}$.

        Mathematics:
        - `int`: $\mathcal{O}(1)$ modular division.
        - `lcg`: $\mathcal{O}(\log m)$ 2-adic bit-lifting for $m = 2^r$, or $\mathcal{O}(\sqrt{m})$ BSGS.
        - `fgraph`: $\mathcal{O}(1)$ orbit hash lookup.
        Raises `Refused` for families without computable closed-form inverses.

        Args:
            target: Target state value.
            max_order: Optional orbit exploration ceiling.

        Returns:
            Smallest coordinate $t \ge 0$, or None if target is unreachable.
        """
        if not self.is_ground:
            raise Refused("a non-ground law cannot be inverted")
        fam = self.family
        p = self.params

        if fam == "int":
            return find_coordinate_int(p["step"], p["mod"], p["x0"], target)

        if fam == "lcg":
            a = p["a"]
            c = p["c"]
            m = p["mod"]
            x0 = p["x0"]
            if m > 0 and (m & (m - 1)) == 0 and (a % 4) == 1:
                cand = find_coordinate_lcg_adic(a, c, m, x0, target)
                if cand is not None:
                    return cand
            return find_coordinate_lcg(a, c, m, x0, target, max_order=max_order)

        if fam == "fgraph":
            orbit = p["orbit"]
            for i, val in enumerate(orbit):
                if val == target:
                    return i
            return None

        raise Refused(f"inversion unsupported for law family {fam!r}")

    def describe(self) -> str:
        r"""Return a human-readable mathematical description of the law."""
        if self.verdict == "TAPE":
            return f"TAPE  residual={self.residual:.3f}"
        if self.family == "int":
            return f"{self.verdict} int step={self.params.get('step')} mod={self.params.get('mod')}"
        if self.family == "lcg":
            return f"{self.verdict} lcg a={self.params.get('a')} c={self.params.get('c')} mod={self.params.get('mod')}"
        if self.family == "gf2":
            return f"{self.verdict} gf2 order={self.order}"
        if self.family == "fgraph":
            return f"{self.verdict} fgraph mu={self.params.get('mu')} lam={self.params.get('lam')}"
        if self.family == "kreg":
            return f"{self.verdict} kreg k={self.params.get('k')}"
        return f"{self.verdict} {self.family}"


def navigate_guarded(law: Law, t: int) -> int:
    r"""Navigate a law while strictly enforcing the PREFIX-GROUND escape horizon.

    Mathematics:
    Guarantees that predictions never exceed the certified horizon:
    \[
    t < t_{\text{horizon}} = \text{first\_bad}
    \]
    Raises `HorizonExceeded` if $t \ge t_{\text{horizon}}$.

    Args:
        law: Certified law instance.
        t: Target coordinate.

    Returns:
        State at coordinate $t$.
    """
    if law.verdict == "PREFIX-GROUND" and law.first_bad is not None and t >= law.first_bad:
        raise HorizonExceeded(
            f"coordinate t={t} exceeds certified horizon first_bad={law.first_bad}"
        )
    return law.navigate(t)


def orbit_leap(law: Law, t: int) -> int:
    r"""Leap the system dynamical state forward to coordinate $t$ in $\mathcal{O}(\log t)$ time.

    Mathematics:
    Evaluates closed-form orbit jump:
    \[
    x_t = \text{navigate\_guarded}(\mathcal{L}, t)
    \]

    Args:
        law: Certified law.
        t: Future time coordinate.

    Returns:
        Predicted state value.
    """
    return navigate_guarded(law, t)


def find_guarded(law: Law, target: int, max_order: int | None = None) -> int | None:
    r"""Invert a law and re-verify the coordinate against forward guarded navigation.

    Mathematics:
    Finds $t = \mathcal{G}^{-1}(\text{target})$ and mandates forward consistency:
    \[
    \mathcal{G}(t) = \text{target}
    \]

    Args:
        law: Certified law.
        target: Target state.
        max_order: Optional search bound.

    Returns:
        Verified coordinate $t$, or None.
    """
    coord = law.find(target, max_order=max_order)
    if coord is None:
        return None
    if navigate_guarded(law, coord) != target:
        raise Refused(f"inversion check failed: find({target})={coord} but forward navigate is divergent")
    return coord


def _divisors_within(g: int, cap: int = 200) -> list[int]:
    r"""Return non-trivial integer divisors of $g$ in descending order."""
    if g <= 1 or g > (1 << 48):
        return []
    ds: list[int] = []
    n = g
    f = 2
    while f * f <= n and f < 10000:
        if n % f == 0:
            e = 0
            while n % f == 0:
                n //= f
                e += 1
            base = f**e
            mult = 1
            for _ in range(e + 1):
                ds.append(base // mult if mult <= base else base)
                mult *= f
        f += 1 if f == 2 else 2
    if n > 1:
        ds.append(n)
    ds.append(g)
    return sorted({d for d in ds if d > 1}, reverse=True)[:cap]


def modulus_candidates(values: Sequence[int], limit: int = 32) -> list[int]:
    r"""Extract candidate moduli from trace samples using the determinant GCD invariant.

    Mathematics:
    For an affine recurrence $x_{t+1} \equiv (a x_t + c) \pmod M$, differences $d_i = x_{i+1} - x_i$ satisfy:
    \[
    d_{i+1} d_{i-1} - d_i^2 \equiv 0 \pmod M
    \]
    Thus $M$ divides $\gcd_i |d_{i+1} d_{i-1} - d_i^2|$.

    Args:
        values: Sequence of observed integers.
        limit: Maximum powers of two to strip.

    Returns:
        List of candidate moduli ordered widest first.
    """
    n = len(values)
    if n < 4:
        return []
    d = [values[i + 1] - values[i] for i in range(n - 1)]
    g = 0
    for i in range(1, len(d) - 1):
        g = gcd(g, abs(d[i + 1] * d[i - 1] - d[i] * d[i]))
    if g == 0:
        for x in d[1:]:
            g = gcd(g, abs(x))

    cands: list[int] = []
    if g > 1:
        cands.append(g)
        gg = g
        for _ in range(limit):
            if gg % 2:
                break
            gg //= 2
            if gg > 1:
                cands.append(gg)
        cands.extend(_divisors_within(g))

    native = [1 << k for k in range(8, 33)]
    famous_primes = [65537, 1000003, 2147483647]
    cands.extend(native)
    cands.extend(famous_primes)

    seen = set()
    out = []
    for m in cands:
        if m > 1 and m not in seen:
            seen.add(m)
            out.append(m)
    return out


def fit_affine(values: Sequence[int], m: int) -> dict[str, int] | None:
    r"""Attempt an exact affine fit $x_{t+1} \equiv (a x_t + c) \pmod M$.

    Mathematics:
    Handles cases where $\gcd(d_0, M) = q > 1$ by reducing to modulus $M / q$:
    \[
    a \equiv (d_1 / q) \cdot (d_0 / q)^{-1} \pmod{M / q}
    \]

    Args:
        values: Integer sequence.
        m: Candidate modulus.

    Returns:
        Dict with `{"a": a, "c": c, "M": M}` or None.
    """
    n = len(values)
    if n < 3:
        return None
    d = [values[i + 1] - values[i] for i in range(n - 1)]
    q = m
    for x in d:
        q = gcd(q, abs(x))
        if q == 1:
            break
    q = max(q, 1)
    mp = m // q
    if mp <= 1:
        return None
    d0 = (d[0] // q) % mp
    d1 = (d[1] // q) % mp
    if d0 == 0 or gcd(d0, mp) != 1:
        return None

    a0 = (d1 * pow(d0, -1, mp)) % mp
    for a in (a0, a0 + mp):
        if a >= m:
            continue
        c = (values[1] - a * values[0]) % m
        cur = values[0] % m
        ok = True
        for v in values:
            if cur != v % m:
                ok = False
                break
            cur = (a * cur + c) % m
        if ok:
            return {"a": a, "c": c, "M": m}
    return None


def fit_kreg(values: Sequence[int], k: int = 2) -> dict[str, Any] | None:
    r"""Attempt to fit a $k$-regular sequence relation.

    Mathematics:
    Checks if for all residues $r \in [0, k - 1]$, there exist $\alpha_r, \beta_r$ such that:
    \[
    x_{k t + r} = \alpha_r x_t + \beta_r, \quad \forall t \ge 0
    \]

    Args:
        values: Sequence of observed integers.
        k: Integer decimation base ($k \in \{2, 3\}$).

    Returns:
        Dict with parameters `{"k": k, "rules": rules, "base_vals": base_vals}` or None.
    """
    n = len(values)
    if n < k * 4:
        return None
    rules: dict[int, tuple[int, int]] = {}
    for r in range(k):
        if k + r >= n:
            return None
        t0, t1 = 0, 1
        y0 = values[r]
        y1 = values[k + r]
        x0 = values[t0]
        x1 = values[t1]
        dx = x1 - x0
        dy = y1 - y0
        if dx == 0:
            if dy != 0:
                return None
            alpha = 1
            beta = y0 - x0
        else:
            if dy % dx != 0:
                return None
            alpha = dy // dx
            beta = y0 - alpha * x0

        t = 0
        while k * t + r < n:
            expected = alpha * values[t] + beta
            if values[k * t + r] != expected:
                return None
            t += 1
        rules[r] = (alpha, beta)

    base_vals = {0: values[0]}
    return {"k": k, "rules": rules, "base_vals": base_vals}


def _evaluate_law_residuals(
    predict_fn: Callable[[int], int],
    samples: Sequence[int],
    n_window: int,
) -> tuple[int, int | None]:
    r"""Count prediction mismatches and identify the first bad coordinate."""
    err = 0
    first_bad = None
    for i, v in enumerate(samples):
        if predict_fn(i) != v:
            err += 1
            if first_bad is None:
                first_bad = i
    return err, first_bad


def recover_law(window: Sequence[int], truth: Sequence[int] | None = None) -> Law:
    r"""Classify an observation sequence onto the lowest sufficient ladder rung.

    Mathematics:
    Given observed window $W$ and withheld validation truth $T$, searches rungs:
    1. GF(2) linear recurrence if samples are binary $\{0, 1\}$.
    2. Integer arithmetic progression ($a = 1$).
    3. Wide-modulus affine recurrence ($a \ne 1$).
    4. $k$-regular sequence for $k \in \{2, 3\}$.
    5. Eventual periodicity / functional-graph cycle detection ($\mu, \lambda$).
    6. TAPE fallback on failure.

    Args:
        window: Training observation sequence.
        truth: Withheld verification sequence.

    Returns:
        Certified `Law` object.
    """
    if not window:
        return Law(family="tape", verdict="TAPE", residual=1.0)
    samples = list(window) + (list(truth) if truth is not None else [])
    n_win = len(window)
    tot = len(samples)
    best_candidate: Law | None = None

    def _consider_cand(cand: Law) -> Law | None:
        r"""Evaluate candidate law against grounding criteria."""
        nonlocal best_candidate
        if cand.verdict == "GROUND" or truth is None:
            return cand
        if cand.verdict == "PREFIX-GROUND" and cand.first_bad is not None and cand.first_bad > n_win:
            if best_candidate is None or cand.residual < best_candidate.residual:
                best_candidate = cand
        return None

    # 1. Binary GF(2)
    if all(v in (0, 1) for v in samples):
        c_coef, l_deg = berlekamp_massey(window, 2)
        if l_deg < n_win // 2:
            init = list(window[:l_deg])

            def pred_gf2(t_idx: int) -> int:
                r"""Predict GF(2) LFSR state."""
                if t_idx < len(init):
                    return init[t_idx]
                return lfsr_jump(c_coef, init, t_idx)[0]

            err, first_bad = _evaluate_law_residuals(pred_gf2, samples, n_win)
            params = {"C": c_coef, "init": init}
            if truth is None:
                return Law(family="gf2", params=params, order=l_deg, verdict="FITTED")
            if err == 0:
                return Law(family="gf2", params=params, order=l_deg, verdict="GROUND", residual=0.0)
            if first_bad is not None and first_bad > n_win:
                cand = Law(
                    family="gf2",
                    params=params,
                    order=l_deg,
                    verdict="PREFIX-GROUND",
                    residual=err / max(1, tot - n_win),
                    first_bad=first_bad,
                )
                hit = _consider_cand(cand)
                if hit:
                    return hit

    # 2 & 3. Affine fits (int and lcg)
    for cand_m in modulus_candidates(samples if truth is not None else window):
        fit = fit_affine(window, cand_m)
        if fit is not None:
            a = fit["a"]
            c = fit["c"]
            m = fit["M"]
            x0 = window[0] % m
            fam = "int" if a == 1 else "lcg"

            def pred_affine(t_idx: int, a_val: int = a, c_val: int = c, m_val: int = m, x0_val: int = x0) -> int:
                r"""Predict affine state."""
                return lcg_navigate(a_val, c_val, m_val, x0_val, t_idx)

            err, first_bad = _evaluate_law_residuals(pred_affine, samples, n_win)
            params = {"a": a, "c": c, "mod": m, "x0": x0}
            if fam == "int":
                params = {"step": c, "mod": m, "x0": x0}

            if truth is None:
                return Law(family=fam, params=params, order=1, verdict="FITTED")
            if err == 0:
                return Law(family=fam, params=params, order=1, verdict="GROUND", residual=0.0)
            if first_bad is not None and first_bad > n_win:
                cand = Law(
                    family=fam,
                    params=params,
                    order=1,
                    verdict="PREFIX-GROUND",
                    residual=err / max(1, tot - n_win),
                    first_bad=first_bad,
                )
                hit = _consider_cand(cand)
                if hit:
                    return hit

    # 4. k-regular
    for k_cand in (2, 3):
        fit_kr = fit_kreg(window, k=k_cand)
        if fit_kr is not None:
            rules = fit_kr["rules"]
            base_vals = fit_kr["base_vals"]

            def _eval_kr(coord: int) -> int:
                r"""Evaluate k-regular recurrence."""
                if coord in base_vals:
                    return base_vals[coord]
                r_res = coord % k_cand
                q_quot = coord // k_cand
                alpha, beta = rules[r_res]
                return alpha * _eval_kr(q_quot) + beta

            err, first_bad = _evaluate_law_residuals(_eval_kr, samples, n_win)
            params = {"k": k_cand, "rules": rules, "base_vals": base_vals}
            if truth is None:
                return Law(family="kreg", params=params, order=k_cand, verdict="FITTED")
            if err == 0:
                return Law(family="kreg", params=params, order=k_cand, verdict="GROUND", residual=0.0)
            if first_bad is not None and first_bad > n_win:
                cand = Law(
                    family="kreg",
                    params=params,
                    order=k_cand,
                    verdict="PREFIX-GROUND",
                    residual=err / max(1, tot - n_win),
                    first_bad=first_bad,
                )
                hit = _consider_cand(cand)
                if hit:
                    return hit

    # 5. Eventual periodicity (fgraph)
    period = detect_eventual_period(window)
    if period is not None:
        mu, lam = period
        orbit = list(window[: mu + lam])

        def pred_fgraph(t_idx: int) -> int:
            r"""Predict periodic orbit state."""
            if t_idx < mu:
                return orbit[t_idx]
            return orbit[mu + (t_idx - mu) % lam]

        err, first_bad = _evaluate_law_residuals(pred_fgraph, samples, n_win)
        params = {"mu": mu, "lam": lam, "orbit": orbit}
        if truth is None:
            return Law(family="fgraph", params=params, order=lam, verdict="FITTED")
        if err == 0:
            return Law(family="fgraph", params=params, order=lam, verdict="GROUND", residual=0.0)
        if first_bad is not None and first_bad > n_win:
            cand = Law(
                family="fgraph",
                params=params,
                order=lam,
                verdict="PREFIX-GROUND",
                residual=err / max(1, tot - n_win),
                first_bad=first_bad,
            )
            hit = _consider_cand(cand)
            if hit:
                return hit

    if best_candidate is not None:
        return best_candidate

    return Law(family="tape", params={}, order=0, verdict="TAPE", residual=1.0)
