r"""Mixture decomposition for interleaved multi-thread execution streams.

Mathematics:
Let $x = (x_0, x_1, \dots, x_{N-1}) \in \mathbb{Z}^N$ be an observation trace
generated by concurrent, round-robin, or multiplexed execution on a shared substrate.
When multiple lawful processes $y^{(0)}, y^{(1)}, \dots, y^{(s-1)}$ are interleaved
with period $s$:
\[
x_{s \cdot q + r} = y^{(r)}_q, \quad 0 \le r < s, \quad q \ge 0
\]
The composite sequence $x$ generally violates individual single-law invariants and
is refused as TAPE by a plain certifier.

Mixture decomposition performs stride decimation over residue classes:
\[
\sigma_{s, r}(x)_q = x_{s \cdot q + r}
\]
searching for the minimal stride $s \in [2, s_{\max}]$ such that every component
$\sigma_{s, r}(x)$ certifies as GROUND under an algebraic law $\mathcal{L}_r$.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from typing import Any, Sequence

from mailcpu.law_certifier import Law, recover_law


@dataclass
class MixtureComponent:
    r"""Certified component of an interleaved sequence mixture.

    Mathematics:
    Represents the sub-law $\mathcal{L}_r$ governing residue class $r \pmod s$:
    \[
    x_{s \cdot q + r} = \mathcal{G}_r(q)
    \]
    """

    residue: int
    family: str
    verdict: str
    order: int
    params: dict[str, Any] = field(default_factory=dict)


@dataclass
class Mixture:
    r"""Decomposition of an interleaved execution trace into parallel lawful components.

    Mathematics:
    Encapsulates interleave period $s$ and component laws $\{\mathcal{L}_0, \dots, \mathcal{L}_{s-1}\}$.
    """

    stride: int
    components: list[MixtureComponent] = field(default_factory=list)

    @property
    def is_mixture(self) -> bool:
        r"""Return True if this represents a non-trivial certified mixture ($s > 1$)."""
        return self.stride > 1 and len(self.components) == self.stride


def decompose_mixture(
    lane: Sequence[int],
    max_stride: int = 8,
    require_refused: bool = True,
) -> Mixture:
    r"""Search for minimal interleave period $s$ separating an execution stream into lawful components.

    Mathematics:
    Searches ascending stride $s \in [2, s_{\max}]$ to find the minimal period where:
    \[
    \forall r \in [0, s-1]: \quad \text{verdict}(\text{recover}(\sigma_{s, r}(x))) \in \{\text{GROUND}, \text{PREFIX-GROUND}\}
    \]
    Searching ascending order avoids selecting higher harmonics ($2s, 3s, \dots$).
    Guarded by `require_refused` so that streams already satisfying a single law are
    never needlessly fractured into mixtures.

    Args:
        lane: Observed integer sequence.
        max_stride: Maximum interleave stride to test.
        require_refused: If True, only attempts decomposition if lane is refused as TAPE.

    Returns:
        `Mixture` instance with discovered stride and components.
    """
    n = len(lane)
    if require_refused:
        # Check if lane is already lawful
        split = max(4, int(n * 0.7))
        base_law = recover_law(lane[:split], lane[split:])
        if base_law.is_ground:
            return Mixture(stride=1)

    for s in range(2, max_stride + 1):
        comps: list[MixtureComponent] = []
        all_ground = True
        for r in range(s):
            sub = lane[r::s]
            if len(sub) < 8:
                all_ground = False
                break
            split = max(4, int(len(sub) * 0.7))
            law = recover_law(sub[:split], sub[split:])
            if not law.is_ground:
                all_ground = False
                break
            comps.append(
                MixtureComponent(
                    residue=r,
                    family=law.family,
                    verdict=law.verdict,
                    order=law.order,
                    params=dict(law.params),
                )
            )
        if all_ground and len(comps) == s:
            return Mixture(stride=s, components=comps)

    return Mixture(stride=1)


def recover_mixture(
    lane: Sequence[int],
    truth: Sequence[int] | None = None,
    max_stride: int = 8,
) -> tuple[Law, Mixture]:
    r"""Certify a sequence with fallback to mixture decomposition.

    Mathematics:
    First evaluates direct single-law certification $\mathcal{L} = \text{recover}(W, T)$.
    If $\mathcal{L}$ is GROUND, returns $(\mathcal{L}, \text{Mixture}(1))$.
    If $\mathcal{L}$ grades TAPE, evaluates $\text{decompose\_mixture}(W \cup T)$.
    If a valid decomposition with stride $s \ge 2$ is found, returns a composite
    mixture law $\mathcal{L}_{\text{mix}}$ capable of closed-form navigation:
    \[
    \mathcal{G}_{\text{mix}}(t) = \mathcal{G}_{t \pmod s}(\lfloor t / s \rfloor)
    \]

    Args:
        lane: Observation window.
        truth: Optional withheld verification truth.
        max_stride: Maximum decomposition stride.

    Returns:
        Tuple of (certified `Law`, `Mixture`).
    """
    base_law = recover_law(lane, truth)
    if base_law.is_ground:
        return base_law, Mixture(stride=1)

    samples = list(lane) + (list(truth) if truth is not None else [])
    mix = decompose_mixture(samples, max_stride=max_stride, require_refused=False)
    if not mix.is_mixture:
        return base_law, Mixture(stride=1)

    families = Counter(c.family for c in mix.components)
    dominant_family = families.most_common(1)[0][0]
    composite_params = {
        "stride": mix.stride,
        "components": [
            {
                "residue": c.residue,
                "family": c.family,
                "order": c.order,
                "params": c.params,
            }
            for c in mix.components
        ],
    }
    composite_law = Law(
        family=f"mixture_{dominant_family}",
        params=composite_params,
        order=mix.stride,
        verdict="GROUND",
        residual=0.0,
        first_bad=None,
    )
    return composite_law, mix
